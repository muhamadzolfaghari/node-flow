export function mermaidArchitectureToTerraform(mermaid) {
  const lines = mermaid.split('\n');
  const groups = [];
  const services = [];

  for (const l of lines) {
    const t = l.trim();
    if (!t || /^architecture/i.test(t)) continue;
    const gm = t.match(/^group\s+([A-Za-z0-9_-]+)(?:\(([^)]*)\))?(?:\[([^\]]*)\])?/);
    if (gm) { groups.push({ id: gm[1], icon: gm[2] || 'cloud', title: gm[3] || gm[1] }); continue; }
    const sm = t.match(/^service\s+([A-Za-z0-9_-]+)(?:\(([^)]*)\))?(?:\[([^\]]*)\])?(?:\s+in\s+([A-Za-z0-9_-]+))?/);
    if (sm) { services.push({ id: sm[1], icon: sm[2] || 'server', title: sm[3] || sm[1], group: sm[4] || null }); continue; }
  }

  if (!groups.length && !services.length) throw new Error('No architecture elements found to export as Terraform.');

  const out = [
    '# Generated by DiagramAtlas / NodeFlow',
    'terraform {',
    '  required_providers {',
    '    aws = {',
    '      source  = "hashicorp/aws"',
    '      version = "~> 5.0"',
    '    }',
    '  }',
    '}',
    '',
    'provider "aws" {',
    '  region = "us-east-1"',
    '}',
    ''
  ];

  for (const g of groups) {
    out.push(`resource "aws_vpc" "${g.id}" {`);
    out.push('  cidr_block           = "10.0.0.0/16"');
    out.push('  enable_dns_hostnames = true');
    out.push('  tags = {');
    out.push(`    Name = "${g.title}"`);
    out.push('  }');
    out.push('}');
    out.push('');
  }

  for (const s of services) {
    if (s.icon === 'database') {
      out.push(`resource "aws_db_instance" "${s.id}" {`);
      out.push(`  identifier        = "${s.id}"`);
      out.push('  engine            = "postgres"');
      out.push('  instance_class    = "db.t4g.micro"');
      out.push('  allocated_storage = 20');
      out.push(`  tags = { Name = "${s.title}" }`);
      out.push('}');
    } else if (s.icon === 'disk') {
      out.push(`resource "aws_s3_bucket" "${s.id}" {`);
      out.push(`  bucket = "${s.id.toLowerCase()}-data-bucket"`);
      out.push(`  tags   = { Name = "${s.title}" }`);
      out.push('}');
    } else {
      out.push(`resource "aws_ecs_service" "${s.id}" {`);
      out.push(`  name            = "${s.id}"`);
      out.push('  cluster         = "core-cluster"');
      out.push(`  task_definition = "${s.id}-task"`);
      out.push('  desired_count   = 2');
      out.push(`  tags            = { Name = "${s.title}" }`);
      out.push('}');
    }
    out.push('');
  }

  return out.join('\n');
}
